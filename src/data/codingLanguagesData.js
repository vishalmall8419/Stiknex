/**
 * Returns all 50 coding exercises/snippets for the given language ID
 */
export function getSnippetsForLanguage(langId) {
  const lang = CODE_LANGUAGES.find(l => l.id === langId) || CODE_LANGUAGES[0];
  const list = [];
  
  for (let idx = 0; idx < CS_50_TOPICS.length; idx++) {
    const topic = CS_50_TOPICS[idx];
    list.push({
      id: idx + 1,
      slug: topic.slug,
      title: `${idx + 1}. ${topic.title}`,
      diff: topic.diff,
      file: `${topic.slug}.${lang.ext}`,
      category: lang.category,
      code: generateSnippetForLang(lang, idx)
    });
  }
  return list;
}

// Procedural generator returning clean, formatted code for all 50 exercises
function generateSnippetForLang(lang, topicIndex) {
  const t = CS_50_TOPICS[topicIndex];
  const langId = lang.id;

  if (langId === 'javascript' || langId === 'typescript') {
    const isTS = langId === 'typescript';
    if (t.slug === 'binary-search') {
      return `function binarySearch(arr${isTS ? ': number[]' : ''}, target${isTS ? ': number' : ''})${isTS ? ': number' : ''} {\n  let low = 0, high = arr.length - 1;\n  while (low <= high) {\n    const mid = Math.floor((low + high) / 2);\n    if (arr[mid] === target) return mid;\n    if (arr[mid] < target) low = mid + 1;\n    else high = mid - 1;\n  }\n  return -1;\n};`;
    }
    if (t.slug === 'debounce-throttle') {
      return `const debounce = (fn${isTS ? ': (...args: any[]) => void' : ''}, delay = 300) => {\n  let timer${isTS ? ': any' : ''};\n  return (...args${isTS ? ': any[]' : ''}) => {\n    clearTimeout(timer);\n    timer = setTimeout(() => fn(...args), delay);\n  };\n};`;
    }
    if (t.slug === 'lru-cache-evict') {
      return `class LRUCache {\n  constructor(capacity${isTS ? ': number' : ''}) {\n    this.capacity = capacity;\n    this.cache = new Map();\n  }\n  get(key${isTS ? ': string' : ''}) {\n    if (!this.cache.has(key)) return -1;\n    const val = this.cache.get(key);\n    this.cache.delete(key);\n    this.cache.set(key, val);\n    return val;\n  }\n}`;
    }
    return `// ${t.title} in ${lang.name}\nexport function ${t.slug.replace(/-/g, '_')}(arr${isTS ? ': number[]' : ''}) {\n  const result = [];\n  for (let i = 0; i < arr.length; i++) {\n    if (arr[i] != null) result.push(arr[i]);\n  }\n  return result;\n}`;
  }

  if (langId === 'python') {
    if (t.slug === 'binary-search') {
      return `def binary_search(arr: list[int], target: int) -> int:\n    low, high = 0, len(arr) - 1\n    while low <= high:\n        mid = (low + high) // 2\n        if arr[mid] == target:\n            return mid\n        elif arr[mid] < target:\n            low = mid + 1\n        else:\n            high = mid - 1\n    return -1`;
    }
    if (t.slug === 'prime-sieve') {
      return `def sieve_of_eratosthenes(limit: int) -> list[int]:\n    primes = [True] * (limit + 1)\n    primes[0] = primes[1] = False\n    for p in range(2, int(limit ** 0.5) + 1):\n        if primes[p]:\n            for i in range(p * p, limit + 1, p):\n                primes[i] = False\n    return [p for p in range(limit + 1) if primes[p]]`;
    }
    return `# ${t.title} in Python\ndef ${t.slug.replace(/-/g, '_')}(items: list) -> list:\n    result = []\n    for item in items:\n        if item is not None:\n            result.append(item)\n    return result`;
  }

  if (langId === 'java') {
    const className = t.slug.split('-').map(s => s.charAt(0).toUpperCase() + s.slice(1)).join('');
    return `// ${t.title} in Java\npublic class ${className} {\n    public static int execute(int[] data, int target) {\n        int left = 0, right = data.length - 1;\n        while (left <= right) {\n            int mid = left + (right - left) / 2;\n            if (data[mid] == target) return mid;\n            if (data[mid] < target) left = mid + 1;\n            else right = mid - 1;\n        }\n        return -1;\n    }\n}`;
  }

  if (langId === 'c' || langId === 'cpp') {
    return `// ${t.title} in ${lang.name}\n#include <stdio.h>\n#include <stdlib.h>\n\nint ${t.slug.replace(/-/g, '_')}(const int *arr, int size, int target) {\n    int low = 0, high = size - 1;\n    while (low <= high) {\n        int mid = low + (high - low) / 2;\n        if (arr[mid] == target) return mid;\n        if (arr[mid] < target) low = mid + 1;\n        else high = mid - 1;\n    }\n    return -1;\n}`;
  }

  if (langId === 'go') {
    const funcName = t.slug.split('-').map(s => s.charAt(0).toUpperCase() + s.slice(1)).join('');
    return `// ${t.title} in Go\npackage main\n\nfunc ${funcName}(arr []int, target int) int {\n\tlow, high := 0, len(arr)-1\n\tfor low <= high {\n\t\tmid := (low + high) / 2\n\t\tif arr[mid] == target {\n\t\t\treturn mid\n\t\t} else if arr[mid] < target {\n\t\t\tlow = mid + 1\n\t\t} else {\n\t\t\thigh = mid - 1\n\t\t}\n\t}\n\treturn -1\n}`;
  }

  if (langId === 'rust' || langId === 'rust_tokio') {
    return `// ${t.title} in Rust\npub fn ${t.slug.replace(/-/g, '_')}(arr: &[i32], target: i32) -> Option<usize> {\n    let mut low = 0;\n    let mut high = arr.len();\n    while low < high {\n        let mid = low + (high - low) / 2;\n        if arr[mid] == target {\n            return Some(mid);\n        } else if arr[mid] < target {\n            low = mid + 1;\n        } else {\n            high = mid;\n        }\n    }\n    None\n}`;
  }

  if (langId === 'sql') {
    return `-- ${t.title} in SQL\nWITH ranked_data AS (\n    SELECT id, name, score,\n           DENSE_RANK() OVER (ORDER BY score DESC) as rank_pos\n    FROM analytics_stream\n    WHERE active = TRUE\n)\nSELECT id, name, score, rank_pos\nFROM ranked_data\nWHERE rank_pos <= 10;`;
  }

  if (langId === 'html') {
    return `<!-- ${t.title} in HTML5 -->\n<div class="coding-card active">\n  <header class="card-header">\n    <h3 class="title">${t.title}</h3>\n    <span class="badge ${t.diff.toLowerCase()}">${t.diff}</span>\n  </header>\n  <main class="card-body">\n    <p>Practice touch typing high-frequency code syntax.</p>\n  </main>\n</div>`;
  }

  if (langId === 'css') {
    return `/* ${t.title} in CSS */\n.coding-container {\n  display: flex;\n  align-items: center;\n  justify-content: space-between;\n  padding: 1.5rem 2rem;\n  background: #0d1117;\n  border-radius: 1rem;\n  box-shadow: 0 10px 25px rgba(0, 0, 0, 0.4);\n}`;
  }

  // Generic idiomatic fallback
  return `// ${t.title} in ${lang.name}\n// Exercise ${topicIndex + 1} of 50 • Difficulty: ${t.diff}\nfn ${t.slug.replace(/-/g, '_')}(input_data: list) {\n    let result = [];\n    for item in input_data {\n        if item != null {\n            result.append(item);\n        }\n    }\n    return result;\n}`;
}
